public class Programa202 {
    public static void main(String[] args) {

        // a) Variables enteras
        int p = 10;
        int q = 20;

        // b) Variables float
        float x = 1.5f;
        float y = 2.75f;
        float z = 3.0f;

        // c) Variables carácter
        char a = 'a';
        char b = 'b';
        char c = 'c';

        // d) Variables double
        double raiz1 = 4.47d;
        double raiz2 = -4.47d;

        // e) Variable entera larga
        long contador = 1000000L;

        // f) Variable entera corta
        short indicador = 5;

        // g) Variable entera
        int indice = 0;

        // h) Variables double
        double precio = 19.99d;
        double precioFinal = 17.99d;

        // i) Variables carácter
        char car1 = 'x';
        char car2 = 'y';

        // j) Variable tipo byte
        byte valor = 100;

        // k) Variables lógicas
        boolean primero = true;
        boolean ultimo = false;

        // l) Variable de tipo cadena de caracteres
        String nombre = "Sandro";

        // Mostramos todas las variables por pantalla
        System.out.println("p: " + p);
        System.out.println("q: " + q);
        System.out.println("x: " + x);
        System.out.println("y: " + y);
        System.out.println("z: " + z);
        System.out.println("a: " + a);
        System.out.println("b: " + b);
        System.out.println("c: " + c);
        System.out.println("raiz1: " + raiz1);
        System.out.println("raiz2: " + raiz2);
        System.out.println("contador: " + contador);
        System.out.println("indicador: " + indicador);
        System.out.println("indice: " + indice);
        System.out.println("precio: " + precio);
        System.out.println("precioFinal: " + precioFinal);
        System.out.println("car1: " + car1);
        System.out.println("car2: " + car2);
        System.out.println("valor: " + valor);
        System.out.println("primero: " + primero);
        System.out.println("ultimo: " + ultimo);
        System.out.println("nombre: " + nombre);
    }
}
